import mongoose from "mongoose";



const invoiceSchema =
new mongoose.Schema({

    /*
    |--------------------------------------------------------------------------
    | Order Reference
    |--------------------------------------------------------------------------
    */

    order: {

        type: mongoose.Schema.Types.ObjectId,

        ref: "orders",

        required: true,

        unique: true
    },



    /*
    |--------------------------------------------------------------------------
    | User Reference
    |--------------------------------------------------------------------------
    */

    user: {

        type: mongoose.Schema.Types.ObjectId,

        ref: "users",

        required: true
    },



    /*
    |--------------------------------------------------------------------------
    | Invoice Number
    |--------------------------------------------------------------------------
    */

    invoiceNumber: {

        type: String,

        required: true,

        unique: true
    },



    /*
    |--------------------------------------------------------------------------
    | PDF URL / File Path
    |--------------------------------------------------------------------------
    */

    pdfUrl: {
        type: String
    },



    /*
    |--------------------------------------------------------------------------
    | Email Status
    |--------------------------------------------------------------------------
    */

    sentToEmail: {

        type: Boolean,

        default: false
    },



    /*
    |--------------------------------------------------------------------------
    | Generated Time
    |--------------------------------------------------------------------------
    */

    generatedAt: {

        type: Date,

        default: Date.now
    }

}, {
    timestamps: true
});



/*
|--------------------------------------------------------------------------
| Indexes
|--------------------------------------------------------------------------
*/

// invoiceSchema.index({
//     order: 1
// });

// invoiceSchema.index({
//     invoiceNumber: 1
// });

invoiceSchema.index({
    user: 1
});



/*
|--------------------------------------------------------------------------
| Export
|--------------------------------------------------------------------------
*/

const invoiceModel =
mongoose.model(
    "invoices",
    invoiceSchema
);

export default invoiceModel;