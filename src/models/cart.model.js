import mongoose from "mongoose";



/*
|--------------------------------------------------------------------------
| Cart Item Schema
|--------------------------------------------------------------------------
*/

const cartItemSchema =
new mongoose.Schema({

    /*
    |--------------------------------------------------------------------------
    | Product Reference
    |--------------------------------------------------------------------------
    */

    product: {

        type: mongoose.Schema.Types.ObjectId,

        ref: "products",

        required: true
    },



    /*
    |--------------------------------------------------------------------------
    | Product Snapshot
    |--------------------------------------------------------------------------
    */

    title: {
        type: String,
        required: true
    },

    thumbnail: {
        type: String
    },



    /*
    |--------------------------------------------------------------------------
    | Selected Variant
    |--------------------------------------------------------------------------
    */

    variant: {

        id: mongoose.Schema.Types.ObjectId,

        color: String,

        size: String,

        sku: String
    },



    /*
    |--------------------------------------------------------------------------
    | Selected Lens Option
    |--------------------------------------------------------------------------
    */

    lensOption: {

        id: mongoose.Schema.Types.ObjectId,

        name: String
    },



    /*
    |--------------------------------------------------------------------------
    | Power Information
    |--------------------------------------------------------------------------
    */

    power: {
        type: Number
    },



    /*
    |--------------------------------------------------------------------------
    | Quantity
    |--------------------------------------------------------------------------
    */

    quantity: {

        type: Number,

        default: 1,

        min: 1
    },



    /*
    |--------------------------------------------------------------------------
    | Pricing Snapshot
    |--------------------------------------------------------------------------
    */

    basePrice: {
        type: Number,
        required: true
    },

    variantPrice: {
        type: Number,
        default: 0
    },

    lensPrice: {
        type: Number,
        default: 0
    },

    powerPrice: {
        type: Number,
        default: 0
    },

    finalPrice: {
        type: Number,
        required: true
    },



    /*
    |--------------------------------------------------------------------------
    | Total Item Price
    |--------------------------------------------------------------------------
    */

    totalPrice: {
        type: Number,
        required: true
    }

}, {
    _id: true
});



/*
|--------------------------------------------------------------------------
| Cart Schema
|--------------------------------------------------------------------------
*/

const cartSchema =
new mongoose.Schema({

    /*
    |--------------------------------------------------------------------------
    | User
    |--------------------------------------------------------------------------
    */

    user: {

        type: mongoose.Schema.Types.ObjectId,

        ref: "users",

        required: true,

        unique: true
    },



    /*
    |--------------------------------------------------------------------------
    | Cart Items
    |--------------------------------------------------------------------------
    */

    items: [cartItemSchema],



    /*
    |--------------------------------------------------------------------------
    | Cart Summary
    |--------------------------------------------------------------------------
    */

    subtotal: {

        type: Number,

        default: 0
    },



    totalItems: {

        type: Number,

        default: 0
    }

}, {
    timestamps: true
});



/*
|--------------------------------------------------------------------------
| Export
|--------------------------------------------------------------------------
*/

const cartModel =
mongoose.model(
    "carts",
    cartSchema
);

export default cartModel;